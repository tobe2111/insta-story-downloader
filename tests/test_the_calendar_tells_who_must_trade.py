            ("지수 편입·편출", "유료"),          # 재료 없음
            ("월말 채권 인덱스", "부분집합"),     # 기존 후보와 중복
            ("국민연금", "결정성"),              # 실시간 관측 불가
            ("절세 매도", "표본"),               # 연 1회 — 판정 자체가 안 난다
            ("국채 입찰", "92%"),                # 기존 월말 후보와 거의 겹친다
