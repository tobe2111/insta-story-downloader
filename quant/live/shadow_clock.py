"""그림자 실험 장부의 시계 — 한 계좌만, 시간은 앞으로만 (2026-09-07).

■ 무엇이 일어나고 있었나 (장부 실측)

일일 배치의 통합 계좌 함수는 하루에 **두 번** 돈다 — 본 계좌(오디션이
고른 챔피언)와 섀도 대조군(진화 없이 최초 기본 챔피언으로 고정). 대조군은
"오디션이 실제로 가치를 더하는가"를 재는 계좌라 **신호 자체가 다르다.**

그런데 배분 사다리·사이징 사다리·2세대·무제약 네 실험은 **같은 장부
파일**에 쓴다. 두 계좌의 판정일이 같은 평일에는 멱등 가드(``== bar``)가
두 번째 줄을 삼켜 아무 일도 안 일어난다 — 그래서 몇 주 동안 아무 표시도
없었다. 갈리는 것은 주말이다: 본 계좌는 코인 봉으로 09-05·09-06을 여는데
대조군은 표본이 모자란 종목이 빠져 09-04에 머문다. 그 결과:

    ... 09-04 · 09-05 · **09-04** · 09-06 · **09-04**
                          ↑ 대조군의 줄이 그대로 끼어든다

실측(2026-09-07): 장부 **10개 × 2줄**. 그리고 오염된 줄이 매번 **마지막
줄**이라, 화면의 대표 숫자 10개가 전부 **다른 계좌의 값**이었다. 화면은
그 옆에 "본 계좌와 같은 신호를 받되…"라고 적고 있었다.

다양성 그림자 둘만 깨끗하다(되감김 0). 그 재료를 줍는 자리가 이미
``use_champions`` 안에 있었기 때문이다 — **필요한 가드가 어떤 모양인지는
저장소가 이미 알고 있었고, 나머지 넷에 안 붙였을 뿐이다.**

■ 이 모듈이 하는 일

본 계좌는 2026-08-16 실전 사고(감사 262) 뒤에 "판정일이 과거로 가면
멈춘다"는 관문을 얻었다. **그림자 장부에는 그 관문이 없었다.** 여기 둔다 —
한 규칙을 다섯 장부가 같이 쓴다.

  · 같은 봉은 '이미 했다'(정상)이고, 과거로 가는 봉은 '입력이 고장났다'
    (사고)다. 둘을 같은 가지에 두면 사고가 정상으로 보인다.
  · 이미 들어온 줄은 **고치지 않는다.** 대신 장부가 스스로 세어
    ``out_of_order``로 말한다 — 조용히 빼면 "원래 그런 곡선이었다"와
    구별되지 않는다.
  · 화면의 대표 숫자는 **마지막으로 쓴 줄**이 아니라 **가장 최신 봉의
    줄**이다. 쓴 순서와 시간 순서가 갈릴 수 있다는 것이 이 사고의 요지다.
"""
from __future__ import annotations

#: 화면에 한 번만 싣는 설명 — 트랙마다 되풀이하면 읽는 사람이 건너뛴다.
MIXED_WHY = (
    "쓴 순서와 봉 순서가 어긋난 줄이 남아 있습니다 — 2026-09-07 이전에는 이 "
    "장부에 본 계좌와 섀도 대조군(진화 없는 계좌) 두 계좌가 함께 썼고, 판정일이 "
    "갈리는 주말에 대조군의 줄이 끼어들었습니다. 지난 줄은 고치지 않고 그대로 "
    "두며, 그 줄들이 보관 창을 벗어나면 이 칸은 저절로 사라집니다.")

BACKWARDS = "backwards"
SAME = "same"
NEW = "new"


def _day(row) -> str:
    return str((row or {}).get("date") or "")


def step(history, bar: str) -> str:
    """이 봉을 어떻게 대할 것인가 — ``new`` · ``same`` · ``backwards``.

    ⚠️ ``same``과 ``backwards``를 한 가지에 두면 안 된다. 앞의 것은 정상
       (재실행)이고 뒤의 것은 사고(다른 계좌의 회차이거나 시세가 뒤처짐)다.
    """
    rows = list(history or ())
    if not rows:
        return NEW
    last = _day(rows[-1])
    now = str(bar or "")
    if now == last:
        return SAME
    return NEW if now > last else BACKWARDS


def latest_row(history):
    """가장 최신 **봉**의 줄 — 마지막으로 **쓴** 줄이 아니다.

    되감긴 줄이 장부에 남아 있으면 둘이 갈린다. 실측(2026-09-07)에서는
    장부 10개 전부에서 갈렸고, 화면이 마지막 줄을 읽어 다른 계좌의 자산을
    발표하고 있었다.
    """
    best = None
    for row in history or ():
        if best is None or _day(row) >= _day(best):
            best = row
    return best


def distinct_days(history) -> int:
    """표본 일수 — 줄 수가 아니라 **서로 다른 날짜의 수**.

    같은 날짜가 두 번 들어오면 줄 수는 표본 크기를 부풀려 말한다.
    """
    return len({_day(r) for r in history or () if _day(r)})


def out_of_order(history) -> dict | None:
    """시간이 거꾸로 간 줄 — 있으면 말하고, 없으면 **아무 말도 안 한다**.

    매일 켜져 있는 표시는 표시가 아니므로 깨끗한 장부에서는 ``None``이다.
    새 줄이 더는 안 생기고 보관 창(KEEP_DAYS)이 지나면 저절로 사라진다.
    """
    rows = list(history or ())
    bad, high = [], None
    for row in rows:
        day = _day(row)
        if high is not None and day <= high:
            bad.append(day)
        else:
            high = day
    if not bad:
        return None
    return {"rows": len(bad), "dates": bad}
