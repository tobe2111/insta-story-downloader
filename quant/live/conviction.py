"""신호의 눈금을 다시 매긴다 — 실험 트랙 셋이 **같은 한 곳**을 쓴다.

사장님 지적(2026-08-23): *"거의 10000달러인데 몇백원씩만 투자 중이야?"*

맞는 지적이었다. 재 보니 미국주식 실험은 자산 10,000 중 평균 320달러
(라운드 평균 3.2%)만 굴리고 있었다. 왜 그런지는 크기 규칙을 펼쳐 보면
바로 보인다.

■ 금액이 정해지는 방식

    한 종목 몫 = 자산 ÷ 종목 수          (8종목이면 1,250달러)
    실제 매수액 = 한 종목 몫 × 확신도     (확신도는 0~1)

확신도는 모델이 말한 상승확률을 이렇게 옮긴 값이다(quant/strategies/ml.py
의 ``_size``):

    확신도 = (상승확률 − 문턱) / (1 − 문턱)      문턱은 보통 0.55

즉 **상승확률이 1.00일 때 비로소 100%**가 된다. "이 주식은 다음 한 시간
안에 반드시 오른다"고 모델이 단언해야 그 종목 몫을 다 쓴다는 뜻이다.

■ 그런데 모델은 그렇게 말한 적이 없다

미국 트랙이 실제로 낸 상승확률(신호가 0이 아닌 44건)을 역산해 보면:

    최소 0.550 · 중앙 0.589 · 최대 0.780
    0.80을 넘은 적 0건 · 0.90을 넘은 적 0건

눈금은 1.00까지 그려져 있는데 바늘은 **0.78까지밖에 가 본 적이 없다.**
눈금의 절반을 한 번도 안 쓴 셈이고, 평소 서 있는 자리(0.589)는 눈금의
9%다. 그래서 1,250달러 몫에서 100달러쯤만 나갔다.

이건 터지는 결함이 아니라 **닿을 수 없는 범위에 눈금을 그려 둔** 것이다
— 이 저장소가 여러 번 만난 모양이다(감사 289: 실적 가드가 라이브러리가
없어 한 번도 발동한 적 없었던 것과 같은 종류다). 장치는 멀쩡히 돌지만
그 장치가 실제로 쓰는 구간은 설계자가 상상한 구간이 아니다.

■ 그래서 무엇을 바꿨나 (2026-08-23, 사장님 결정)

눈금의 끝을 1.00이 아니라 **0.70**에 둔다. 모델이 "10번 중 7번은 오른다"
고 말하면 그 종목 몫을 다 쓴다.

    새 확신도 = (상승확률 − 문턱) / (0.70 − 문턱)      (1.0에서 자른다)

같은 기록으로 다시 계산하면 미국 트랙의 투입 비중은 평균 3.2% → 9.0%,
최대 8.1% → 22.1%가 된다.

⚠️ **이건 더 버는 장치가 아니다.** 투입이 커지면 손익이 **양쪽 다** 커진다.
   지금 이 트랙은 손실 구간이고(−0.17%), 같은 기간을 새 눈금으로 돌렸다면
   대략 −0.47%였을 것으로 추정된다. 크게 굴리는 것이 곧 잘하는 것은 아니다.

⚠️ **챔피언은 옛 눈금으로 뽑혔다.** 오디션은 ``_size``의 원래 눈금으로
   성적을 매겼으므로, 지금 도는 것은 그 오디션이 잰 것과 크기 규칙이 다르다.
   그래서 실험 페이지에 '규칙이 바뀐 날'로 공개 기록한다 — 곡선을 읽는
   사람이 어디서 무엇이 달라졌는지 알아야 한다.

⚠️ **본 계좌(100만 챌린지)에는 걸지 않는다.** 사장님 결정이 '실험만'이었고,
   실제 원금이 걸린 쪽의 위험을 같이 키우지 않기 위해서다. 그래서 이
   재보정은 ``_size``를 고치지 않고 **실험 트랙의 신호 경로에서만** 곱한다.

⚠️ **확률에서 온 신호에만** 건다. 규칙 전략(이동평균 교차 등)의 신호는
   확률이 아니라 그냥 방향값이라, 여기에 배수를 곱하면 아무 근거 없이
   포지션만 키우는 것이 된다. 이진(binary) 사이징도 이미 0 아니면 1이라
   재보정할 눈금 자체가 없다.
"""
from __future__ import annotations

# 눈금의 끝 — "10번 중 7번은 오른다"면 그 종목 몫을 다 쓴다.
FULL_CONVICTION_PROB = 0.70

# 이 재보정이 켜진 날. 이전 회차는 옛 눈금이며 **고치지 않는다.**
RECALIBRATED_ON = "2026-08-23"

RULE_CHANGE = {
    "on": RECALIBRATED_ON,
    "what": "확신도 눈금의 끝을 상승확률 1.00에서 0.70으로 당겼습니다 "
            "— 같은 예측에도 더 큰 금액이 나갑니다.",
    "why": "모델이 상승확률 0.80을 넘은 적이 한 번도 없어, 종목 몫의 "
           "10%쯤만 쓰이고 있었습니다. 이 날 이전 회차는 옛 눈금이며 "
           "그 기록은 고치지 않았습니다. 크게 굴린다고 더 버는 것은 "
           "아니며, 손실도 같은 배로 커집니다.",
}


def conviction_scale(spec, full_prob: float = FULL_CONVICTION_PROB) -> float:
    """이 종목의 신호에 곱할 배수. 재보정이 안 맞는 경우 1.0(그대로).

    확률 사이징의 원래 눈금 폭은 ``1 − 문턱``이고, 새 눈금 폭은
    ``full_prob − 문턱``이다. 배수는 두 폭의 비다.

    ⚠️ 1.0을 돌려주는 경우가 여럿이다. 전부 "재보정할 눈금이 없다"는 뜻이지
       "재보정이 필요 없다"는 뜻이 아니다 — 확률이 아닌 신호를 확률처럼
       늘리면 그건 근거 없이 베팅을 키우는 것이다.
    """
    if not isinstance(spec, dict) or spec.get("strategy") != "ml":
        return 1.0                      # 규칙 전략의 신호는 확률이 아니다
    params = spec.get("params")
    params = params if isinstance(params, dict) else {}
    if str(params.get("sizing") or "proba") != "proba":
        return 1.0                      # 이진 사이징은 이미 0 아니면 1이다
    try:
        th = float(params.get("threshold") or 0.55)
        top = float(full_prob)
    except (TypeError, ValueError):
        return 1.0
    old_span = 1.0 - th                 # 옛 눈금 폭 (문턱 → 확률 1.00)
    new_span = top - th                 # 새 눈금 폭 (문턱 → full_prob)
    # 문턱이 새 눈금 끝보다 높거나(예: 0.75) 눈금이 뒤집힌 설정이면 손대지
    # 않는다. 여기서 음수 배수를 돌려주면 신호의 **부호가 뒤집혀** 사려던
    # 것을 팔게 된다 — 조용히 정반대로 도는 사고다.
    if not (old_span > 0.0) or not (new_span > 0.0):
        return 1.0
    scale = old_span / new_span
    return scale if scale > 1.0 else 1.0


def recalibrate(sig, spec, *, allow_short: bool = False,
                full_prob: float = FULL_CONVICTION_PROB):
    """신호 하나를 새 눈금으로 옮긴다. 부호는 지키고 ±1에서 자른다.

    ``allow_short``가 False면 음수는 관망(0.0)이다 — 롱 전용 트랙에서
    음수를 그대로 두면 체결 규칙이 숏을 연다.
    """
    try:
        x = float(sig)
    except (TypeError, ValueError):
        return None
    if x != x:                          # NaN — 모른다는 뜻이다. 지어내지 않는다.
        return None
    x *= conviction_scale(spec, full_prob)
    lo = -1.0 if allow_short else 0.0
    return max(lo, min(1.0, x))


def spec_of(strategy) -> dict:
    """전략 객체에서 눈금에 필요한 것만 뽑아 spec 모양으로 만든다.

    ⚠️ 왜 객체에서 읽나. 실험 트랙은 챔피언 규칙을 **빌려 쓰고**, 검사는
       가짜 전략을 주입한다. 장부에서 spec을 따로 조회하면 주입된 가짜
       신호에 진짜 챔피언의 배수가 곱해진다 — 검사와 운영이 다른 것을
       재게 된다. 신호를 낸 그 객체에게 물어보는 것이 맞다.

    ⚠️ 속성 이름이 바뀌면 이 함수는 조용히 "ML이 아님"으로 답하고, 재보정은
       아무 말 없이 꺼진다. 그래서 ① 실제 챔피언들이 1.0이 아닌 배수를
       받는지 검사가 확인하고, ② 회차 기록에 **실제로 적용된 배수**를 남긴다.
       조용히 꺼진 장치는 이 저장소에서 가장 위험한 것이다.
    """
    if not hasattr(strategy, "threshold") or not hasattr(strategy, "sizing"):
        return {}
    return {"strategy": "ml",
            "params": {"threshold": getattr(strategy, "threshold", None),
                       "sizing": getattr(strategy, "sizing", None)}}


def scale_of(strategy, full_prob: float = FULL_CONVICTION_PROB) -> float:
    """전략 객체가 받을 배수. 확률 사이징이 아니면 1.0."""
    return conviction_scale(spec_of(strategy), full_prob)
