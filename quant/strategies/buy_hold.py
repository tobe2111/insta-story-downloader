"""보유(Buy & Hold) — 아무것도 하지 않는 전략. **우리가 이겨야 하는 상대다.**

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
⚠️ 왜 '전략'으로 만들었나 (2026-08-14)

사이트는 "그냥 보유" 곡선을 벤치마크로 그려 보여준다. 그런데 **오디션 링에는
그 벤치마크가 없었다.** 매일 밤 20종목에서 후보 20여 명이 챔피언에게 도전하는데,
그 목록에 '아무것도 안 하기'가 빠져 있었다.

그래서 시스템은 구조적으로 **"그냥 들고 있는 게 낫다"를 발견할 수 없었다.**
화면에는 그 사실이 그려지고 있는데, 판단 루프는 그걸 후보로 세워 본 적이 없다.

실측(2026-08-14, 스냅샷 20종목·수수료 미반영):
    ML 전략 샤프 중앙값 0.46  ·  단순 보유 0.81
    ML 방향 적중률 54.3%(3,512봉) — 문서가 말하는 52~55% 범위와 일치
즉 예측은 정상적으로 작동하는데, 노출이 ~30%뿐이라 상승장에서 구조적으로 진다.

이건 '고칠 버그'가 아니라 **매일 다시 물어야 할 질문**이다. 사람이 한 번
알아채고 지나가는 대신, 링에 세워 두면 오디션이 매일 답한다.
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

⚠️ 정직한 한계 — 보유가 이긴다는 것이 '보유가 옳다'는 뜻은 아니다.
   · 보유는 **하락을 그대로 다 맞는다.** 샤프가 높아도 최대낙폭은 대개 훨씬
     크고, 사람이 실제로 못 버티고 포기하는 지점이 거기다.
   · 지금 데이터로 잰 우위의 일부는 **생존 편향**이다(README 참조) —
     사라진 종목은 이 비교에 아예 등장하지 않는다.
   · 그래서 이 전략도 다른 후보와 **똑같은 2단계 관문**을 통과해야만
     챔피언이 된다. 통과하면 그것 역시 정직한 결과이고, 장부에 그대로 남는다.
   · 승격되더라도 총노출은 변동성 타깃·킬스위치·검증 게이트가 다시 깎는다.
"""
from __future__ import annotations

import pandas as pd

from quant.strategies.base import Strategy


class BuyHold(Strategy):
    """항상 목표 비중 1.0 — 첫 봉부터 끝까지 들고 있는다.

    warmup을 두는 이유: 다른 전략들은 지표 계산에 앞부분을 쓰느라 초반에
    관망한다. 보유만 0봉부터 실리면 그 구간의 수익이 통째로 보유 쪽에
    붙어 대결이 불공정해진다(비교 구간이 다른 것과 같다). 기본 0이지만
    오디션에서 필요하면 맞출 수 있게 손잡이를 남긴다.
    """

    name = "buy_hold"

    def __init__(self, warmup: int = 0, weight: float = 1.0,
                 allow_short: bool = False):
        self.warmup = max(0, int(warmup))
        # 1.0을 넘길 수 없다 — 레버리지는 이 전략의 주제가 아니다.
        self.weight = min(1.0, max(0.0, float(weight)))
        # 다른 전략과 생성 인터페이스를 맞추기 위해 받는다(전략 계약 검사가
        # 전 전략에 이 인자를 넘긴다). **동작에는 영향이 없다** — '보유'는
        # 정의상 롱이고, 숏으로 들고 있는 것은 다른 이야기다.
        self.allow_short = bool(allow_short)

    def generate_signals(self, df: pd.DataFrame) -> pd.Series:
        signal = pd.Series(self.weight, index=df.index)
        if self.warmup:
            signal.iloc[:self.warmup] = 0.0
        return self._finalize(signal, df.index)
